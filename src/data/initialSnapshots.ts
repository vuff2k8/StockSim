/**
 * Builds full instruments for a given market with authentic historical candles
 */
export function getInitialMarketInstruments(marketId: string, customSeed: number = 42): Instrument[] {
  let rawList: Omit<Instrument, 'history'>[] = [];

  switch (marketId) {
    case 'vietnam':
      rawList = VIETNAM_INSTRUMENTS_DATA;
      break;
    case 'us':
      rawList = US_INSTRUMENTS_DATA;
      break;
    case 'japan':
      rawList = JAPAN_INSTRUMENTS_DATA;
      break;
    case 'singapore':
      rawList = SINGAPORE_INSTRUMENTS_DATA;
      break;
    case 'europe':
      rawList = EUROPE_INSTRUMENTS_DATA;
      break;
    case 'global':
      rawList = [
        ...US_INSTRUMENTS_DATA.slice(0, 4),
        ...VIETNAM_INSTRUMENTS_DATA.slice(0, 3).map((item) => ({
          ...item,
          market: 'global',
          currency: 'USD',
          currentPrice: Number((item.currentPrice / 25000).toFixed(2)),
          previousClose: Number((item.previousClose / 25000).toFixed(2)),
          openPrice: Number((item.openPrice / 25000).toFixed(2)),
          dayHigh: Number((item.dayHigh / 25000).toFixed(2)),
          dayLow: Number((item.dayLow / 25000).toFixed(2)),
        })),
        ...JAPAN_INSTRUMENTS_DATA.slice(0, 2).map((item) => ({
          ...item,
          market: 'global',
          currency: 'USD',
          currentPrice: Number((item.currentPrice / 150).toFixed(2)),
          previousClose: Number((item.previousClose / 150).toFixed(2)),
          openPrice: Number((item.openPrice / 150).toFixed(2)),
          dayHigh: Number((item.dayHigh / 150).toFixed(2)),
          dayLow: Number((item.dayLow / 150).toFixed(2)),
        })),
      ];
      break;
    default:
      rawList = VIETNAM_INSTRUMENTS_DATA;
  }

  const now = new Date();

  return rawList.map((inst, index) => {
    // Generate deterministic 30-day candles
    const history = generateHistoricalCandles(inst.currentPrice, inst.volatility, 30, now);
    return {
      ...inst,
      history,
    };
  });
}
