import { Candle, Instrument } from '../types/market';

function generateHistoricalCandles(
  basePrice: number,
  volatility: number,
  days: number = 30,
  referenceDate: Date = new Date()
): Candle[] {
  const candles: Candle[] = [];
  let price = basePrice * (1 - (Math.random() - 0.5) * 0.1); // slight drift from 30 days ago
  const now = referenceDate.getTime();
  const dayMs = 24 * 60 * 60 * 1000;

  for (let i = days; i >= 0; i--) {
    const time = new Date(now - i * dayMs).toISOString().split('T')[0] + 'T15:00:00.000Z';
    const dailyReturn = (Math.random() - 0.49) * volatility * 1.5;
    const open = price;
    const close = i === 0 ? basePrice : Math.max(price * 0.1, open * (1 + dailyReturn));
    const high = Math.max(open, close) * (1 + Math.random() * volatility * 0.8);
    const low = Math.min(open, close) * (1 - Math.random() * volatility * 0.8);
    const volume = Math.floor(basePrice > 1000 ? 500_000 + Math.random() * 2_000_000 : 2_000_000 + Math.random() * 10_000_000);

    candles.push({
      timestamp: time,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    price = close;
  }

  return candles;
}

